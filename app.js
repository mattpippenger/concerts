  // ---- Fun stats ---------------------------------------------------------
  function funStats() {
    var facts = [];
    // busiest year
    var busiest = YEARS.slice().sort(function (a, b) { return yearCounts[b] - yearCounts[a]; })[0];
    facts.push(fact("Busiest year", busiest, yearCounts[busiest] + " shows", {nav: 'year', year: busiest}));
    // average per active year
    var avg = (SHOWS.length / YEARS.length).toFixed(1);
    facts.push(fact("Avg / active year", avg, "shows per year"));
    // most-seen decade
    var dec = {};
    SHOWS.forEach(function (s) { if (s.year) { var d = Math.floor(s.year / 10) * 10; dec[d] = (dec[d] || 0) + 1; } });
    var topDec = Object.keys(dec).sort(function (a, b) { return dec[b] - dec[a]; })[0];
    facts.push(fact("Top decade", topDec + "s", dec[topDec] + " shows"));
    // first show
    if (DATED[0]) facts.push(fact("First show ever", DATED[0].headliner, prettyDate(DATED[0].date), {nav: 'artist', name: groupOf(DATED[0].headliner)}));
    // longest gap between shows
    var gap = longestGap();
    if (gap) {
      var gapTo = gap.to.split('-');
      facts.push(fact("Longest dry spell", gap.days + " days", prettyDate(gap.from) + " → " + prettyDate(gap.to),
        {nav: 'otd', month: +gapTo[1], day: +gapTo[2]}));
    }
    // bands seen once
    var once = ARTISTS.filter(function (a) { return a.count === 1; }).length;
    facts.push(fact("One-and-done bands", once, "seen exactly once"));
    // most concerts in a single month
    var monthCount = {};
    DATED.forEach(function (s) {
      if (s.year && s.month) {
        var mk = s.year + '-' + s.month;
        monthCount[mk] = (monthCount[mk] || 0) + 1;
      }
    });
    var topMonthKey = Object.keys(monthCount).sort(function (a, b) { return monthCount[b] - monthCount[a]; })[0];
    if (topMonthKey) {
      var tmParts = topMonthKey.split('-');
      var tmYear = +tmParts[0], tmMonth = +tmParts[1];
      facts.push(fact("Biggest month", MONTHS_LONG[tmMonth - 1] + " " + tmYear,
        monthCount[topMonthKey] + " shows", {nav: 'year', year: tmYear}));
    }
    // most common state/city
    var stateCount = {};
    SHOWS.forEach(function (s) { if (s.state) stateCount[s.state] = (stateCount[s.state] || 0) + 1; });
    var topState = Object.keys(stateCount).sort(function (a, b) { return stateCount[b] - stateCount[a]; })[0];
    if (topState) facts.push(fact("Home turf", topState, stateCount[topState] + " shows", {nav: 'search', q: topState}));
    // unique states
    var uniqueStates = Object.keys(stateCount).length;
    if (uniqueStates) facts.push(fact("States visited", uniqueStates, "different states"));
    // milestone shows
    [50, 100, 150, 200, 250, 300].forEach(function (m) {
      var s = DATED[m - 1];
      if (s) facts.push(fact(ordinal(m) + " show", s.headliner, prettyDate(s.date), {nav: 'artist', name: groupOf(s.headliner)}));
    });

    return '<div class="view-head">Fun Facts</div><div class="factgrid">' + facts.join("") + '</div>';
  }
  function fact(k, v, sub, nav) {
    var inner = '<div class="k">' + esc(k) + '</div><div class="v">' + esc(v) + '</div>' +
                (sub ? '<div class="sub">' + esc(sub) + '</div>' : '');
    if (!nav) return '<div class="fact">' + inner + '</div>';
    var attrs = 'type="button" class="fact fact-link"';
    for (var key in nav) { if (nav.hasOwnProperty(key)) attrs += ' data-' + key + '="' + esc(String(nav[key])) + '"'; }
    return '<button ' + attrs + '>' + inner + '</button>';
  }
  function wireFacts() {
    Array.prototype.forEach.call(document.querySelectorAll('.fact-link'), function (b) {
      b.addEventListener('click', function () {
        var nav = b.getAttribute('data-nav');
        if (nav === 'artist') {
          showDetail('artist', b.getAttribute('data-name'));
        } else if (nav === 'year') {
          searchState.year = +b.getAttribute('data-year');
          searchState.q = '';
          setView('search');
        } else if (nav === 'otd') {
          otdDate = { m: +b.getAttribute('data-month'), d: +b.getAttribute('data-day') };
          setView('onthisday');
        } else if (nav === 'search') {
          searchState.q = b.getAttribute('data-q');
          searchState.year = null;
          setView('search');
        }
      });
    });
  }
  function longestGap() {
    var best = null;
    for (var i = 1; i < DATED.length; i++) {
      var a = new Date(DATED[i - 1].date), b = new Date(DATED[i].date);
      var days = Math.round((b - a) / 86400000);
      if (!best || days > best.days) best = { days: days, from: DATED[i - 1].date, to: DATED[i].date };
    }
    return best;
  }

  // ---- Search ------------------------------------------------------------
  var searchState = { q: "", year: null };
  function viewSearch() {
    var years = YEARS.slice().reverse();
    var chips = '<button class="chip' + (searchState.year ? "" : " is-active") + '" data-year="">All years</button>' +
      years.map(function (y) {
        return '<button class="chip' + (searchState.year === y ? " is-active" : "") +
               '" data-year="' + y + '">' + y + '</button>';
      }).join("");
    app.innerHTML =
      '<div class="view-head">Search the stub box</div>' +
      '<div class="searchbar"><input id="q" placeholder="Search any band, venue, city, or year&hellip;" ' +
        'autocomplete="off" value="' + esc(searchState.q) + '" /></div>' +
      '<div class="search-controls" id="year-chips">' + chips + '</div>' +
      '<div id="results"></div>';
    var input = el("q");
    input.addEventListener("input", function () { searchState.q = input.value; runSearch(); });
    Array.prototype.forEach.call(document.querySelectorAll("#year-chips .chip"), function (c) {
      c.addEventListener("click", function () {
        var y = c.getAttribute("data-year");
        searchState.year = y ? +y : null;
        viewSearch();
      });
    });
    input.focus();
    runSearch();
  }
  function runSearch() {
    var q = searchState.q.trim().toLowerCase();
    var res = SHOWS.filter(function (s) {
      if (searchState.year && s.year !== searchState.year) return false;
      if (!q) return true;
      if (String(s.year).indexOf(q) >= 0) return true;
      if (s.venue.toLowerCase().indexOf(q) >= 0) return true;
      if (s.venueRaw.toLowerCase().indexOf(q) >= 0) return true;   // old/raw venue text
      if (s.venueAka.some(function (a) { return a.toLowerCase().indexOf(q) >= 0; })) return true;
      if ((s.city + " " + s.state).toLowerCase().indexOf(q) >= 0) return true;
      return s.bands.some(function (b) { return b.toLowerCase().indexOf(q) >= 0; });
    }).sort(function (a, b) {
      var ad = a.date || "0000", bd = b.date || "0000";
      return ad > bd ? -1 : ad < bd ? 1 : b.id - a.id;
    });
    var box = el("results");
    box.innerHTML =
      '<div class="view-head" style="margin-top:6px">' +
        (q || searchState.year ? "Results" : "All shows") +
        '<span class="count-pill">' + res.length + ' show' + (res.length === 1 ? "" : "s") + '</span></div>' +
      ticketsHtml(res);
  }

