  function longestGap() {
    var best = null;
    for (var i = 1; i < DATED.length; i++) {
      var a = new Date(DATED[i - 1].date), b = new Date(DATED[i].date);
      var days = Math.round((b - a) / 86400000);
      if (!best || days > best.days) best = { days: days, from: DATED[i - 1].date, to: DATED[i].date };
    }
    return best;
  }

