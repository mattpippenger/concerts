  var otdDate = null;  // {m, d} currently viewed
  function viewOnThisDay() {
    var today = otdDate || (function () { var n = new Date(); return { m: n.getMonth() + 1, d: n.getDate() }; })();
    var matches = DATED.filter(function (s) { return s.month === today.m && s.day === today.d; })
                       .sort(function (a, b) { return b.year - a.year; });

    var dateInput = '<input type="date" id="otd-picker" />';
    var head =
      '<div class="view-head">On This Day &mdash; ' + MONTHS_LONG[today.m - 1] + ' ' + today.d +
        '<span class="count-pill">' + matches.length + ' show' + (matches.length === 1 ? "" : "s") + '</span>' +
      '</div>' +
      '<div class="search-controls"><span class="chip" style="cursor:default">Jump to a date:</span>' + dateInput +
        '<button class="chip" id="otd-today">Today</button></div>';

    var body;
    if (!matches.length) {
      body = '<div class="empty">No shows on ' + MONTHS_LONG[today.m - 1] + ' ' + today.d +
             ' &mdash; yet. Try another date above.</div>';
    } else {
      // milestone callouts
      var miles = [];
      matches.forEach(function (s) {
        if (s.ordinal % 50 === 0 || s.ordinal === 1 || s.ordinal === 25 || s.ordinal === 100 ||
            s.ordinal === 200 || s.ordinal === 300) {
          miles.push(milestone("Milestone show",
            "On this date in <b>" + s.year + "</b> you saw your <b>" + ordinal(s.ordinal) +
            " show ever</b> &mdash; " + esc(s.headliner) + "."));
        }
        var nth = nthSeen(s.headliner, s);
        var gname = groupOf(s.headliner);   // count is grouped, so name the artist
        if (nth === 1) {
          miles.push(milestone("First time",
            "On this date in <b>" + s.year + "</b> you saw <b>" + esc(gname) +
            "</b> for the first time."));
        } else if (nth && nth % 5 === 0) {
          miles.push(milestone("Repeat offender",
            "This was your <b>" + ordinal(nth) + " time</b> seeing <b>" + esc(gname) +
            "</b> (" + s.year + ")."));
        }
      });
      body = miles.join("") + ticketsHtml(matches);
    }
    app.innerHTML = head + body;

    var picker = el("otd-picker");
    if (picker) {
      // show current date in the picker (use a representative recent year)
      var yyyy = new Date().getFullYear();
      picker.value = yyyy + "-" + pad2(today.m) + "-" + pad2(today.d);
      picker.addEventListener("change", function () {
        var p = parts(picker.value);
        if (p) { otdDate = { m: p.m, d: p.d }; viewOnThisDay(); }
      });
    }
    var tbtn = el("otd-today");
    if (tbtn) tbtn.addEventListener("click", function () { otdDate = null; viewOnThisDay(); });
  }
