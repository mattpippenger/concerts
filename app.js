  var THEME_STORE = "concertTrackerTheme";
  function applyTheme(key) {
    if (key) document.documentElement.setAttribute("data-theme", key);
    else document.documentElement.removeAttribute("data-theme");
    try { localStorage.setItem(THEME_STORE, key); } catch (e) {}
    Array.prototype.forEach.call(document.querySelectorAll(".swatch"), function (s) {
      s.classList.toggle("is-active", s.getAttribute("data-theme-key") === key);
    });
  }
  function buildThemePicker() {
    var host = el("theme-picker");
    if (!host) return;
    THEMES.forEach(function (t) {
      var b = document.createElement("button");
      b.className = "swatch";
      b.setAttribute("data-theme-key", t.key);
      b.innerHTML = '<span class="dots">' +
        t.dots.map(function (c) { return '<i style="background:' + c + '"></i>'; }).join("") +
        '</span>' + esc(t.name);
      b.addEventListener("click", function () { applyTheme(t.key); });
      host.appendChild(b);
    });
    var saved = "";
    try { saved = localStorage.getItem(THEME_STORE) || ""; } catch (e) {}
    applyTheme(saved);
  }

